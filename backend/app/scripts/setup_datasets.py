#!/usr/bin/env python3
"""
Dataset setup and validation script for Certificate Verification System.
"""
import sys
import os
import argparse
from pathlib import Path

# Add the backend directory to Python path
sys.path.insert(0, str(Path(__file__).parent.parent))

from app.core.config import settings
from app.utils.dataset_validator import dataset_validator

def setup_datasets():
    """Set up and validate datasets for the certificate verification system."""
    print("Certificate Verification System - Dataset Setup")
    print("=" * 60)
    
    # Print current configuration
    print("\nCurrent Configuration:")
    print(f"SSL Dataset Directory: {settings.SSL_DATASET_DIR}")
    print(f"SSL Dataset File: {settings.SSL_DATASET_FILE}")
    print(f"Certificate Dataset Directory: {settings.CERTIFICATE_DATASET_DIR}")
    print(f"Certificate Data YAML: {settings.CERTIFICATE_DATA_YAML}")
    print(f"Model Directory: {settings.MODEL_DIR}")
    
    # Validate datasets
    print("\nValidating Datasets...")
    print("-" * 30)
    
    validation_results = dataset_validator.validate_all_datasets()
    
    # Print detailed report
    report = dataset_validator.create_dataset_report()
    print(report)
    
    # Provide recommendations
    print("\nRecommendations:")
    print("-" * 20)
    
    if validation_results["overall_status"] == "valid":
        print("✓ All datasets are properly configured and ready to use!")
    elif validation_results["overall_status"] == "partial":
        print("⚠ Some datasets are missing or have issues:")
        
        ssl_result = validation_results["ssl_dataset"]
        cert_result = validation_results["certificate_dataset"]
        
        if not ssl_result["valid"]:
            print(f"\n  SSL Dataset Issues:")
            print(f"  - Expected location: {settings.get_ssl_dataset_path()}")
            print(f"  - Make sure the SSL certificate dataset CSV file exists")
            print(f"  - You can download it or update the SSL_DATASET_DIR environment variable")
        
        if not cert_result["valid"]:
            print(f"\n  Certificate Dataset Issues:")
            print(f"  - Expected location: {settings.get_certificate_dataset_path()}")
            print(f"  - Make sure the certificate detection dataset exists with train/ and val/ folders")
            print(f"  - Each folder should contain images/ and labels/ subdirectories")
    else:
        print("✗ Critical dataset issues found:")
        print("  - Check that your dataset directories exist")
        print("  - Verify the paths in your .env file or environment variables")
        print("  - Ensure you have the required dataset files")
    
    # Environment variable suggestions
    print(f"\nEnvironment Variables:")
    print(f"You can customize dataset paths by setting these environment variables:")
    print(f"  SSL_DATASET_DIR={settings.SSL_DATASET_DIR}")
    print(f"  SSL_DATASET_FILE={settings.SSL_DATASET_FILE}")
    print(f"  CERTIFICATE_DATASET_DIR={settings.CERTIFICATE_DATASET_DIR}")
    print(f"  CERTIFICATE_DATA_YAML={settings.CERTIFICATE_DATA_YAML}")
    
    return validation_results["overall_status"] == "valid"

def create_sample_env():
    """Create a sample .env file with current dataset paths."""
    env_path = Path(".env")
    
    if env_path.exists():
        print(f"⚠ .env file already exists at {env_path}")
        response = input("Do you want to overwrite it? (y/N): ")
        if response.lower() != 'y':
            print("Skipping .env file creation")
            return
    
    # Get current working directory for relative paths
    cwd = Path.cwd()
    
    env_content = f"""# Certificate Verification System Configuration
# Generated by setup_datasets.py

# Database Configuration
MONGO_URL=mongodb://localhost:27017
MONGO_DB_NAME=certificate_verification

# Dataset Configuration
SSL_DATASET_DIR={settings.SSL_DATASET_DIR}
SSL_DATASET_FILE={settings.SSL_DATASET_FILE}
CERTIFICATE_DATASET_DIR={settings.CERTIFICATE_DATASET_DIR}
CERTIFICATE_DATA_YAML={settings.CERTIFICATE_DATA_YAML}

# Model and Upload Directories
MODEL_DIR={settings.MODEL_DIR}
UPLOAD_DIR={settings.UPLOAD_DIR}
STATIC_DIR={settings.STATIC_DIR}

# Security (generate a proper secret key for production)
SECRET_KEY=your-secret-key-change-this-in-production

# OCR Configuration (set path to tesseract executable if needed)
TESSERACT_CMD=

# CORS Settings
BACKEND_CORS_ORIGINS=http://localhost:3000,http://localhost:8000,http://localhost:8080

# Tamper Detection
TAMPER_DETECTION_THRESHOLD=0.85
"""
    
    with open(env_path, 'w') as f:
        f.write(env_content)
    
    print(f"✓ Created .env file at {env_path}")
    print("  Please review and update the configuration as needed")

def main():
    """Main function for the dataset setup script."""
    parser = argparse.ArgumentParser(description="Setup and validate datasets for Certificate Verification System")
    parser.add_argument("--create-env", action="store_true", help="Create a sample .env file")
    parser.add_argument("--validate-only", action="store_true", help="Only validate datasets, don't create files")
    
    args = parser.parse_args()
    
    if args.create_env:
        create_sample_env()
        print()
    
    # Always run validation
    success = setup_datasets()
    
    if success:
        print("\n✓ Dataset setup completed successfully!")
        sys.exit(0)
    else:
        print("\n⚠ Dataset setup completed with issues. Please review the recommendations above.")
        sys.exit(1)

if __name__ == "__main__":
    main()